"""Private file storage adapter. Local disk now; implement StorageBackend for S3-compatible storage later."""
from __future__ import annotations

import uuid
from abc import ABC, abstractmethod
from pathlib import Path

from app.core.config import get_settings


class StorageBackend(ABC):
    @abstractmethod
    def save(self, user_id: uuid.UUID, data: bytes, ext: str) -> str: ...
    @abstractmethod
    def read(self, user_id: uuid.UUID, stored_name: str) -> bytes: ...
    @abstractmethod
    def delete(self, user_id: uuid.UUID, stored_name: str) -> None: ...
    @abstractmethod
    def delete_all(self, user_id: uuid.UUID) -> None: ...
    @abstractmethod
    def writable(self) -> bool: ...


class LocalStorage(StorageBackend):
    def __init__(self, root: str):
        self.root = Path(root).resolve()

    def _dir(self, user_id: uuid.UUID) -> Path:
        d = self.root / str(user_id)
        d.mkdir(parents=True, exist_ok=True)
        return d

    def _path(self, user_id: uuid.UUID, stored_name: str) -> Path:
        # stored_name is always generated by us; still refuse anything that is not a plain file name
        if Path(stored_name).name != stored_name or stored_name.startswith("."):
            raise ValueError("invalid stored name")
        return self._dir(user_id) / stored_name

    def save(self, user_id: uuid.UUID, data: bytes, ext: str) -> str:
        name = f"{uuid.uuid4().hex}.{ext}"
        self._path(user_id, name).write_bytes(data)
        return name

    def read(self, user_id: uuid.UUID, stored_name: str) -> bytes:
        return self._path(user_id, stored_name).read_bytes()

    def delete(self, user_id: uuid.UUID, stored_name: str) -> None:
        self._path(user_id, stored_name).unlink(missing_ok=True)

    def delete_all(self, user_id: uuid.UUID) -> None:
        d = self.root / str(user_id)
        if d.exists():
            for f in d.iterdir():
                f.unlink(missing_ok=True)
            d.rmdir()

    def writable(self) -> bool:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            probe = self.root / ".probe"
            probe.write_text("ok")
            probe.unlink()
            return True
        except OSError:
            return False


def get_storage() -> StorageBackend:
    return LocalStorage(get_settings().UPLOAD_DIR)
